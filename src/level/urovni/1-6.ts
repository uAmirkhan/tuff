// Уровень 1-6 «Прорыв». Погоня: снизу поднимается обвал, бег вверх по ступеням и стенам.
import type { Uroven } from '../format';

// Шахта x=0..16, подъём змейкой: ступени вправо, стена, ступени влево, стена, ступени вправо
const stupeni = (x0: number, y0: number, napr: 1 | -1, n: number) => {
  const p: Uroven['poligony'] = [];
  for (let i = 0; i < n; i++) {
    const x = x0 + napr * i * 1.6;
    const y = y0 + i * 0.9;
    const a = napr === 1 ? x : x - 1.6;
    p.push({
      tochki: [
        [a, y - 6],
        [a + 1.6, y - 6],
        [a + 1.6, y],
        [a, y],
      ],
    });
  }
  return p;
};

