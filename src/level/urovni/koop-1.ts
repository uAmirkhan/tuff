//   ледяной уступ 1,8-2,2 — не берёт ни одиночка, ни двое рядом, берёт только слитая пара;
//   ледяной уступ 2,6 и выше — не берёт никто.
//
// Лёд выбран потому, что Вязкость к нему не липнет: на базальте одиночка залез бы по стене.
//
// Второе правило, найденное бот-проверкой 25.09: ворота, решение которых «оба жмут в одну
// сторону», пассажиром проходятся всегда — партнёр держит «вперёд» и этого хватает. Поэтому
// старт стоит ВПЛОТНУЮ к воротам, и разбег берётся назад, влево. Партнёр, который тупо держит
// «вперёд», не даёт паре отойти: слитая пара от встречного ввода встаёт намертво.
//
// Правило геометрии, найденное замером: разбег обязан идти по ТОЙ ЖЕ плоскости, что и подножие
// стены. Если подходить по приподнятой площадке, окно закрывается — слитая пара перестаёт брать
// даже 1,4. Поэтому в комнате всё на одном полу, а обучающий блок игроки перелезают и спускаются.
